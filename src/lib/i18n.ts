export const DICTS: Record<Lang, Dict> = { fr, en };

export function resolveLang(setting: LangSetting | undefined): Lang {
  if (setting === "fr" || setting === "en") return setting;
  const nav = typeof navigator !== "undefined" ? navigator.languages?.[0] ?? navigator.language : "en";
  return /^fr\b/i.test(nav ?? "") ? "fr" : "en";
}

export function useT(): Dict {
  const data = useData();
  return DICTS[resolveLang(data.settings.lang)];
}

export const getT = (): Dict => DICTS[resolveLang(getData().settings.lang)];
